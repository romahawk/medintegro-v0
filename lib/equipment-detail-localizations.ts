import type { Locale } from "@/lib/i18n"

type DetailItem = {
  title: string
  description: string
}

type ProductLocalization = {
  shortDescription?: string
  overview?: string
  heroTitle?: string
  heroSubtitle?: string
  highlights?: string[]
  capabilityItems?: DetailItem[]
  deploymentItems?: DetailItem[]
  valuePoints?: string[]
}

type LocalizedProduct<T extends { slug: string }> = T & ProductLocalization

function localizeProduct<T extends { slug: string }>(
  product: T,
  locale: Locale,
  localizations: Record<string, ProductLocalization>
): LocalizedProduct<T> {
  if (locale !== "ua") {
    return product as LocalizedProduct<T>
  }

  const localized = localizations[product.slug]

  if (!localized) {
    return product as LocalizedProduct<T>
  }

  return {
    ...product,
    ...localized,
  }
}

